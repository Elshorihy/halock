/**
 * HALOCK — Worker auth crypto (Web Crypto only; works in Cloudflare Workers & Node 20+).
 *
 * Security rules (spec §13):
 *  - Passwords are NEVER stored in plain text: PBKDF2-SHA256, 150k iterations, random salt.
 *  - Session tokens are stored as SHA-256 hashes — a DB leak does not leak tokens.
 *  - Verification uses a constant-time comparison.
 */

const PBKDF2_ITERATIONS = 150_000;
const SALT_BYTES = 16;
const KEY_BYTES = 32;

function toHex(buf: ArrayBuffer | Uint8Array): string {
  const bytes = buf instanceof Uint8Array ? buf : new Uint8Array(buf);
  return [...bytes].map((b) => b.toString(16).padStart(2, "0")).join("");
}

function fromHex(hex: string): Uint8Array {
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i++) {
    out[i] = parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  }
  return out;
}

function constantTimeEqual(a: string, b: string): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) {
    diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  }
  return diff === 0;
}

async function pbkdf2(password: string, salt: Uint8Array, iterations: number): Promise<Uint8Array> {
  const keyMaterial = await crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(password),
    "PBKDF2",
    false,
    ["deriveBits"],
  );
  const bits = await crypto.subtle.deriveBits(
    {
      name: "PBKDF2",
      hash: "SHA-256",
      salt: salt as unknown as BufferSource,
      iterations,
    },
    keyMaterial,
    KEY_BYTES * 8,
  );
  return new Uint8Array(bits);
}

/** Format: pbkdf2$<iterations>$<saltHex>$<hashHex> */
export async function hashPassword(password: string): Promise<string> {
  const salt = crypto.getRandomValues(new Uint8Array(SALT_BYTES));
  const hash = await pbkdf2(password, salt, PBKDF2_ITERATIONS);
  return `pbkdf2$${PBKDF2_ITERATIONS}$${toHex(salt)}$${toHex(hash)}`;
}

export async function verifyPassword(password: string, stored: string): Promise<boolean> {
  try {
    const [scheme, iterStr, saltHex, hashHex] = stored.split("$");
    if (scheme !== "pbkdf2") return false;
    const iterations = Number(iterStr);
    if (!Number.isFinite(iterations) || iterations < 10_000 || iterations > 2_000_000) return false;
    const salt = fromHex(saltHex);
    const expected = hashHex.toLowerCase();
    const actual = await pbkdf2(password, salt, iterations);
    return constantTimeEqual(toHex(actual), expected);
  } catch {
    return false;
  }
}

export interface GeneratedToken {
  /** Give this to the user (once). */
  token: string;
  /** Store only this. */
  tokenHash: string;
}

export function generateSessionToken(): GeneratedToken {
  const bytes = crypto.getRandomValues(new Uint8Array(32));
  const token = toHex(bytes);
  return { token, tokenHash: sha256Hex(token) };
}

export function sha256Hex(input: string): string {
  // Synchronous SHA-256 is not in Web Crypto; use a small pure implementation
  // so hashing works in tests and Workers without async plumbing in hot paths.
  return sha256(input);
}

